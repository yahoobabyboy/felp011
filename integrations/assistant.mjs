async function send() {
  const input = $("input");
  const text = input.value.trim();
  if (!text) { input.focus(); return; }
  /* Do not silently swallow the click. A latched busy flag used to make Send do
     nothing at all, forever, with no explanation. */
  if (busy) {
    banner("Still working on the previous change. The button unlocks on its own " +
      "after " + (BUSY_TIMEOUT_MS / 1000) + "s — or reload the page to resync.");
    return;
  }

  input.value = ""; input.style.height = "auto";
  setBusy(true);

  thread.querySelector(".empty")?.remove();
  const el = document.createElement("div");
  el.className = "msg user";
  el.innerHTML = '<div class="who">you</div><div class="bubble">' + esc(text) + "</div>";
  thread.appendChild(el);
  scroll();

  let ok = false;
  try {
    const res = await fetch("/_assistant/chat", {
      method: "POST", headers: { "content-type": "application/json" },
      body: JSON.stringify({ text }),
    });
    if (res.ok) { ok = true; return; }
    const data = await res.json().catch(() => ({}));
    banner(esc(data.error || "Could not reach the assistant.") +
      (data.hint ? "<br><code>" + esc(data.hint) + "</code>" : ""));
  } catch {
    banner("Could not reach /_assistant/chat.");
  }

  setBusy(false);
  /* Never lose what was typed on a failed send. */
  if (!ok) { input.value = text; input.focus(); el.remove(); }
}

/* Recover a wedged turn: re-send what the artist last said, or clear the
   notice and let them carry on. The message text is the real one from the
   transcript rather than anything reconstructed, so a retry is the same
   request, not a paraphrase. */
thread.addEventListener("click", async (e) => {
  const unstick = e.target.closest("button[data-unstick]");
  if (unstick) {
    unstick.disabled = true;
    unstick.textContent = "Unblocking…";
    try {
      const res = await fetch("/_assistant/abort", { method: "POST" });
      if (!res.ok) {
        const data = await res.json().catch(() => ({}));
        banner(esc(data.error || "Could not unblock the turn."));
        unstick.disabled = false;
        unstick.textContent = "Unblock the turn";
        return;
      }
      banner("The turn was stopped. Nothing was changed — ask for it again.");
    } catch {
      banner("Could not reach /_assistant/abort.");
      unstick.disabled = false;
      unstick.textContent = "Unblock the turn";
    }
    await refreshMessages();
    return;
  }
  const retry = e.target.closest("button[data-retry]");
  if (retry) {
    retry.disabled = true;
    retry.textContent = "Asking…";
    if (!lastUserText) {
      retry.disabled = false;
      retry.textContent = "Ask again";
      banner("There is no earlier message to send again.");
      return;
    }
    $("input").value = lastUserText;
    await send();
    return;
  }
  const dismiss = e.target.closest("button[data-dismiss]");
  if (dismiss) {
    dismiss.closest(".msg")?.remove();
    return;
  }
  const b = e.target.closest("button[data-revert]");
  if (!b) return;
  const messageID = b.dataset.revert;
  b.disabled = true; b.textContent = "Undoing…";
  try {
    const res = await fetch("/_assistant/revert", {
      method: "POST", headers: { "content-type": "application/json" },
      body: JSON.stringify({ messageID }),
    });
    const data = await res.json();
    if (!res.ok) { banner(esc(data.error || "Revert failed.")); b.disabled = false; b.textContent = "Undo this change"; return; }
    b.textContent = "Reverted";
    await Promise.all([refreshMessages(), loadDiff()]);
  } catch { b.disabled = false; b.textContent = "Undo this change"; }
});

