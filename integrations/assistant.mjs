function openModal(html, target, onGo) {
  $("modalBody").innerHTML = html;
  $("modal").hidden = false;
  const go = $("modalGo"), cancel = $("modalCancel");
  const close = () => { $("modal").hidden = true; };
  async function run() {
    go.disabled = true;
    go.textContent = "Publishing…";
    const message = $("commitMsg").value;
    try {
      const res = await fetch("/_assistant/publish", {
        method: "POST", headers: { "content-type": "application/json" },
        body: JSON.stringify({ confirm: "publish", message, target }),
      });
      const data = await res.json().catch(() => ({}));
      $("modalBody").innerHTML = data.ok
        ? "<p>Pushed <code>" + esc(data.pushedTo) + "</code> at <code>" + esc(data.sha) +
          "</code>." + (data.live
            ? " Cloudflare will now build and deploy this to the <strong>live site</strong>."
            : " Cloudflare will build a <strong>preview</strong>; the live site is unchanged.") + "</p>"
        : "<div class='warn'>" + esc(data.error || "Publish failed.") + "</div>" +
          (data.hint ? "<p>" + esc(data.hint) + "</p>" : "") +
          "<p class='empty'>Nothing was lost — your files are still on disk.</p>";
      go.textContent = "Close";
      go.disabled = false;
      go.onclick = close;
      $("commitMsg")?.remove();
      await Promise.all([refreshMessages(), loadDiff()]);
      return;
    } catch {
      $("modalBody").innerHTML = "<div class='warn'>Could not reach /_assistant/publish.</div>";
      go.disabled = false; go.textContent = "Commit & push";
    }
  }
  go.onclick = run;
  cancel.addEventListener("click", close);
  $("modal").onclick = (e) => { if (e.target === $("modal")) close(); };
}

$("publish").addEventListener("click", async () => {
  const btn = $("publish");
  btn.disabled = true;
  try {
    const res = await fetch("/_assistant/publish/preview", { method: "POST" });
    const data = await res.json();
    const p = data.preview;
    if (!p) { banner("Could not work out what would be published."); return; }

    let html = "<p>This commits <strong>every</strong> uncommitted change in " +
      esc(p.root) + ". It is not limited to what the assistant changed.</p>";

    if (p.unpublishedCommits > 0) {
      html += "<p><strong>" + p.unpublishedCommits +
        "</strong> commit(s) on this branch are not on the remote yet.</p>";
    }
    if (p.files.length === 0) {
      html += "<p class='empty'>The working tree is clean. " +
        (p.unpublishedCommits ? "Only the commits above would be pushed." : "Nothing to publish.") + "</p>";
    } else {
      html += "<ul class='files'>" + p.files.map((f) =>
        "<li><span class='st'>" + esc(f.code) + "</span><span>" + esc(f.file) +
        "</span></li>").join("") + "</ul>";
    }
    if (p.diffstat) {
      html += "<details class='diff'><summary>Full diffstat</summary><div class='files'>" +
        "<pre class='patch'>" + esc(p.diffstat) + "</pre></div></details>";
    }
    html += "<label class='hint' style='display:block;margin-top:14px'>Commit message</label>" +
      "<textarea id='commitMsg' rows='2'>content: update the site</textarea>";

    /* Two targets, because they are genuinely different outcomes and the
       user must not have to guess which one updates the live site. */
    const onMain = p.branch === "main";
    const choices = '<div class="modal-actions" style="margin-top:16px;justify-content:flex-start">' +
      '<button id="goBranch">Push branch <span class="hint" style="margin:0">' +
      (onMain ? "(preview)" : "— preview only") + "</span></button>" +
      (onMain ? "" :
        '<button id="goMain" class="danger">Push to main — update the live site</button>') +
      "</div>";

    openModal(html + choices, "branch");
    /* Keep whatever the human already typed as the commit message. */
    const reask = (target) => {
      const typed = $("commitMsg") && $("commitMsg").value;
      if (typed) {
        const open = "<textarea id='commitMsg' rows='2'>";
        const start = html.indexOf(open);
        const end = html.indexOf("</textarea>", start);
        if (start !== -1 && end !== -1) {
          const safe = typed.replace(/[&<>]/g,
            (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;" }[c]));
          html = html.slice(0, start) + open + safe + html.slice(end);
        }
      }
      openModal(html, target);
    };
    $("goBranch").onclick = () => reask("branch");
    if (!onMain) $("goMain").onclick = () => reask("main");
  } catch {
    banner("Could not reach /_assistant/publish/preview.");
  } finally {
    btn.disabled = false;
  }
});

