async function boot() {
  const dot = $("dot"), text = $("statusText");
  try {
    const health = await (await fetch("/_assistant/health")).json();
    if (!health.ok) {
      dot.className = "dot down";
      text.textContent = "opencode not running";
      banner("The opencode server is not running, so the assistant cannot answer.<br><br>" +
        "Start it in a second terminal:<br><code>opencode serve --port 4096 --hostname 127.0.0.1</code><br><br>" +
        "Then reload this page.");
      return;
    }
    dot.className = "dot up";
    text.textContent = "opencode " + health.version;

    const s = await (await fetch("/_assistant/session")).json();
    sessionID = s.sessionID;
    if (s.branch) {
      const pill = $("branchPill");
      pill.hidden = false;
      pill.textContent = "branch: " + s.branch;
    }
    await refreshMessages();
    await loadDiff();
    connect();
    $("input").focus();
  } catch {
    dot.className = "dot down";
    text.textContent = "unreachable";
  }
}
