let seenParts = new Set();

/* Build an empty turn node for a message we have not drawn yet, instead of
   re-rendering the whole thread. Re-rendering used to blow away the user's
   just-sent bubble whenever a part arrived for an unknown message. */
function turnNode(messageID, agent) {
  const el = document.createElement("div");
  el.className = "msg assistant";
  el.dataset.messageID = messageID;
  el.dataset.seenText = "";
  el.innerHTML = '<div class="who">' + esc(agent || "assistant") + '</div>' +
    '<div class="bubble"><span class="empty">(working…)</span></div>';
  thread.appendChild(el);
  return el;
}

function applyPart(part) {
  if (!part || !part.messageID) return;
  seenParts.add(part.id);
  let holder = thread.querySelector('[data-messageID="' + part.messageID + '"]');
  if (!holder) holder = turnNode(part.messageID, part.agent);

  /* Reasoning is tracked for liveness and never drawn. */
  if (part.type === "reasoning" || part.type === "step-start") {
    holder.dataset.working = "1";
    return;
  }
  if (part.type === "step-finish") {
    delete holder.dataset.working;
    holder.dataset.done = "1";
    return;
  }

  if (part.type === "text") {
    const bubble = holder.querySelector(".bubble");
    if (!bubble) return;
    const seen = (holder.dataset.seenText || "").split(" ").filter(Boolean);
    /* A turn can contain text -> tool -> text. Only ever writing the first
       part meant the final answer stayed invisible until a full re-render. */
    if (seen.includes(part.id)) return;
    seen.push(part.id);
    holder.dataset.seenText = seen.join(" ");
    const empty = bubble.querySelector(".empty");
    if (empty) {
      bubble.textContent = part.text;
      const who = holder.querySelector(".who");
      if (who && part.agent) who.textContent = part.agent;
      scroll();
    } else if (part.text && part.text.trim()) {
      const p = document.createElement("p");
      p.className = "more";
      p.textContent = part.text;
      bubble.appendChild(p);
      scroll();
    }
  }
  if (part.type === "tool" && part.tool !== "question") {
    if (!holder.querySelector(".work")) {
      const work = document.createElement("details");
      work.className = "work";
      work.innerHTML = "<summary>Working…</summary>";
      holder.appendChild(work);
    }
    const work = holder.querySelector(".work");
    const tools = holder.querySelector(".tools") || (() => {
      const t = document.createElement("div");
      t.className = "tools";
      work.appendChild(t);
      return t;
    })();
    const atBottom = $("main").scrollHeight - $("main").scrollTop - $("main").clientHeight < 90;
    tools.insertAdjacentHTML("beforeend", toolLine(part));
    /* Count after appending, or the label lags one step behind. */
    const sum = work.querySelector("summary");
    if (sum) {
      const n = tools.children.length;
      sum.textContent = "Did " + n + " step" + (n === 1 ? "" : "s");
    }
    if (atBottom) scroll();
  }
  if (part.type === "patch" && (part.files || []).length && !holder.querySelector("[data-revert]")) {
    const actions = document.createElement("div");
    actions.className = "turn-actions";
    actions.innerHTML = '<button data-revert="' + esc(part.messageID) + '">Undo this change</button>';
    holder.appendChild(actions);
  }
}

let es = null;
function connect() {
  if (es) es.close();
  es = new EventSource("/_assistant/events");
  es.onmessage = (e) => {
    let ev; try { ev = JSON.parse(e.data); } catch { return; }
    const p = ev.properties || {};
    /* Drop everything that is not our session. Without this, events from any
       other opencode session on the machine used to re-render this thread and
       wipe the message the user had just sent. */
    if (p.sessionID && sessionID && p.sessionID !== sessionID) return;

    if (ev.type === "message.part.updated") applyPart(p.part);
    else if (ev.type === "session.idle") {
      setBusy(false);
      refreshMessages();
      loadDiff();
    } else if (ev.type === "permission.asked" || ev.type === "question.asked" ||
               ev.type === "question.v2.asked") {
      showPrompt(ev);
    } else if (ev.type === "session.error") {
      setBusy(false);
      banner("The assistant hit an error: " + esc(JSON.stringify(p.error || {}).slice(0, 300)));
    }
  };
  es.onerror = () => { /* EventSource retries on its own */ };
}

async function refreshMessages() {
  try {
    const res = await fetch("/_assistant/messages");
    const data = await res.json();
    if (!data.messages) return;
    const atBottom = $("main").scrollHeight - $("main").scrollTop - $("main").clientHeight < 90;
    renderAll(data.messages, data.pending);
    renderPending(data.pending);
    if (atBottom) scroll();
  } catch {}
}

