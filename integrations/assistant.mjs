/* Kept deliberately short. The artist is a photographer, so a logo or a
   screengrab should both work, but an .html or .svg upload served from the
   site's own origin is a script-injection vector, not a picture. */
const ALLOWED_IMAGE_EXT = [
  ".jpg", ".jpeg", ".png", ".webp", ".avif", ".gif", ".heic",
];

/**
 * Magic bytes, so a .png that is actually a script does not land in public/.
 *
 * Signatures only, no decode: this is here to reject a renamed text file, not
 * to be a validator. Anything not recognised is refused rather than guessed
 * at, because the cost of a wrong "no" is a clear error message while the
 * cost of a wrong "yes" is a file served from your own origin.
 */
const looksLikeImage = (buf) => {
  const b = buf.subarray(0, 16);
  const starts = (...bytes) => bytes.every((v, i) => b[i] === v);
  /* JPEG: FF D8 FF */
  if (starts(0xff, 0xd8, 0xff)) return true;
  /* PNG: 89 50 4E 47 0D 0A 1A 0A */
  if (starts(0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a)) return true;
  /* GIF: "GIF8" */
  if (b.subarray(0, 4).toString("latin1") === "GIF8") return true;
  /* RIFF....WEBP - AVIF and HEIC are ISO-BMFF: ....ftypavif / ftypheic */
  if (b.subarray(0, 4).toString("latin1") === "RIFF" &&
      b.subarray(8, 12).toString("latin1") === "WEBP") return true;
  const brand = b.subarray(4, 12).toString("latin1");
  if (brand.startsWith("ftyp")) {
    const type = brand.slice(4, 8);
    if (["avif", "avis", "heic", "heix", "hevc", "heim", "heis", "mif1", "msf1"].includes(type)) {
      return true;
    }
  }
  return false;
};

