const json = (res, status, body) => {
  const payload = JSON.stringify(body);
  res.writeHead(status, {
    "content-type": "application/json; charset=utf-8",
    "cache-control": "no-store",
  });
  res.end(payload);
};

const readBody = (req, limit = 2_000_000) =>
  new Promise((resolve, reject) => {
    const chunks = [];
    let size = 0;
    req.on("data", (c) => {
      size += c.length;
      if (size > limit) {
        reject(new Error("body too large"));
        req.destroy();
        return;
      }
      chunks.push(c);
    });
    req.on("end", () => {
      const raw = Buffer.concat(chunks).toString("utf8");
      if (!raw) return resolve({});
      try {
        resolve(JSON.parse(raw));
      } catch (err) {
        reject(new Error("invalid JSON body"));
      }
    });
    req.on("error", reject);
  });

export default function assistant(options = {}) {
  const host = options.host ?? "127.0.0.1";
  const port = Number(options.port ?? 4096);
  const base = `http://${host}:${port}`;

  return {
    name: "assistant",
    hooks: {
      "astro:server:setup": ({ server, logger, refreshContent }) => {
        // One shared session for the dev server. The page never handles a
        // session id, so there is nothing for the browser to get wrong.
        let sessionID = null;
        let sessionPromise = null;

        const upstream = async (path, init) => {
          const res = await fetch(base + path, init);
          if (!res.ok) {
            const text = await res.text().catch(() => "");
            throw new Error(`opencode ${path} -> ${res.status} ${text.slice(0, 200)}`);
          }
          return res;
        };

        const health = async () => {
          try {
            const res = await fetch(`${base}/global/health`, {
              signal: AbortSignal.timeout(1500),
            });
            if (!res.ok) throw new Error(String(res.status));
            return await res.json();
          } catch {
            return null;
          }
        };

        /** Create (or reuse) the assistant session. */
        const ensureSession = async (fresh = false) => {
          if (fresh) {
            sessionID = null;
            sessionPromise = null;
          }
          if (sessionID) return sessionID;
          if (!sessionPromise) {
            sessionPromise = (async () => {
              const res = await upstream("/session", {
                method: "POST",
                headers: { "content-type": "application/json" },
                body: JSON.stringify({
                  title: "design assistant",
                  agent: "build",
                  permission: SESSION_PERMISSION,
                }),
              });
              const session = await res.json();
              sessionID = session.id;
              logger.info(`assistant: opencode session ${sessionID}`);
              return sessionID;
            })().catch((err) => {
              sessionPromise = null;
              throw err;
            });
          }
          return sessionPromise;
        };

        /**
         * Server-side twin of the browser's safeFileName.
         *
         * Deliberately not shared with the client script: that one is a string
         * baked into the page, this one runs in Node, and sharing them across
         * the template boundary is how a half-escaped regex ends up deleting
         * somebody's home directory. Keep the two in step by hand.
         */
        const safeUploadName = (raw) => {
          const base = String(raw ?? "")
            .split(/[/\\]/)
            .pop()
            .trim();
          if (!base || base === "." || base === "..") return "";
          const ext = path0.extname(base).toLowerCase().slice(0, 12);
          const stem = path0
            .basename(base, path0.extname(base))
            .toLowerCase()
            .replace(/[^a-z0-9]+/g, "-")
            .replace(/^-+|-+$/g, "")
            .slice(0, 60);
          /* If the name was all punctuation, e.g. "***.png", keep something
             readable rather than returning a bare extension. */
          return (stem || "image") + ext;
        };

        /**
         * Copy the editable sources aside before a turn runs.
         *
         * Deliberately not git: the artist has not committed anything, so
         * `git restore` would happily throw away a day of their work along
         * with the assistant's mistake. These are plain files, kept for a
         * week, and named by the assistant session so a bad turn can be
         * traced back to the message that caused it.
         */
        const snapshot = async () => {
          const root = options.root ?? process.cwd();
          const stamp = new Date().toISOString().replace(/[:.]/g, "-");
          const dir = path0.join(os.tmpdir(), "felp011-assistant", stamp);
          try {
            for (const dir0 of ["src", "public/admin", "scripts"]) {
              const from = path0.join(root, dir0);
              if (!(await fs.access(from).then(() => true).catch(() => false))) continue;
              await fs.cp(from, path0.join(dir, dir0), {
                recursive: true,
                filter: (p) => !p.includes("node_modules") && !p.includes("/.git"),
              });
            }
            /* Keep the last few, so this cannot grow without bound. */
            const home = path0.join(os.tmpdir(), "felp011-assistant");
            const old = (await fs.readdir(home).catch(() => []))
              .filter((n) => n !== stamp)
              .sort();
            for (const n of old.slice(0, Math.max(0, old.length - 6))) {
              await fs.rm(path0.join(home, n), { recursive: true, force: true });
            }
            return { dir };
          } catch (err) {
            /* Never block a chat because a backup failed. */
            logger.warn(`assistant: snapshot failed: ${err?.message ?? err}`);
            return null;
          }
        };

        /**
         * Image requests raised by the ask_for_image tool.
         *
         * The tool blocks on a poll, so this is the other half of that
         * contract: the model asks, the page renders a picker from the list
         * here, and the tool learns the saved path. Held in memory on purpose —
         * an uncollected photograph is not a durable artefact, and writing it
         * to disk would only leave the artist's half-finished uploads lying
         * around in tmp.
         */
        const imageRequests = new Map();
        const IMAGE_REQUEST_TTL = 30 * 60 * 1000;

        const openImageRequests = () => {
          const now = Date.now();
          for (const [id, r] of imageRequests) {
            if (now - r.createdAt > IMAGE_REQUEST_TTL) imageRequests.delete(id);
          }
          return [...imageRequests.entries()]
            .filter(([, r]) => r.status === "pending")
            /* Only the current session's pickers. A tool call carries its
               session id, so a request left over from a session the artist has
               since reset or walked away from is unreachable — showing it
               would put a file dialog on screen that nothing will answer. */
            .filter(([, r]) => !r.sessionID || r.sessionID === sessionID)
            .map(([id, r]) => ({ id, ...r, sessionID: undefined }));
        };

        const answerImageRequest = (id, patch) => {
          const req = imageRequests.get(id);
          if (!req || req.status !== "pending") return false;
          /* Skip nulls rather than assigning them. A field the caller did not
             fill in means "no opinion", and overwriting a value that is
             already there with null would quietly lose it. */
          for (const [k, v] of Object.entries(patch)) {
            if (v === null || v === undefined) continue;
            req[k] = v;
          }
          return true;
        };

        /**
         * The image slots that actually exist, read from the content entries.
         *
         * Guessing slot names produces a picker full of entries that are not
         * there, which is worse than no picker: the artist picks "the piece
         * about the harbour" and writes a line about it. So the list is
         * derived from the files on disk, and site-wide slots are stated
         * plainly because those are conventions, not files.
         */
        const imageSlots = async (collection) => {
          const root = options.root ?? process.cwd();
          const want = (n) => !collection || collection === n;
          const slots = [];
          const push = (id, title, current, kind, file) =>
            slots.push({ id, title, current: current || null, kind, file });

          if (want("site")) {
            push("site: home page hero", "Home page hero", null, "site", "public/media/");
            push("site: about page portrait", "About page portrait", null, "site", "public/media/");
            push("site: shared social image", "Shared social / link image", null, "site", "public/media/");
          }

          /* Minimal frontmatter reader. gray-matter is not a dependency here
             and adding one to read a title line would be a silly cost, so
             this reads the flat scalar keys the schemas actually use. */
          const frontmatter = (text) => {
            if (!text.startsWith("---")) return {};
            const end = text.indexOf("\n---", 3);
            const out = {};
            if (end === -1) return out;
            for (const line of text.slice(3, end).split("\n")) {
              const m = /^([A-Za-z_][\w]*):\s*(.*)$/.exec(line);
              if (!m) continue;
              const value = m[2].trim().replace(/^["']|["']$/g, "");
              if (value && !value.startsWith("{") && !value.startsWith("[")) {
                out[m[1]] = value;
              }
            }
            return out;
          };

          const collectionDir = async (name) => {
            const dir = path0.join(root, "src", "content", name);
            const entries = await fs.readdir(dir, { withFileTypes: true }).catch(() => []);
            return entries.filter((e) => e.isDirectory());
          };

          for (const [name, label] of [["pieces", "piece"], ["stories", "story"]]) {
            if (!want(name)) continue;
            /* The same entry exists once per locale, under the same filename.
                   That is one slot for the artist, not three, so key on the
                   stem and let the first locale that has a title supply it. */
            const byId = new Map();
            for (const locale of await collectionDir(name)) {
              const dir = path0.join(root, "src", "content", name, locale.name);
              const files = (await fs.readdir(dir).catch(() => []))
                .filter((f) => f.endsWith(".md"))
                .sort();
              for (const file of files) {
                const fm = frontmatter(
                  await fs.readFile(path0.join(dir, file), "utf8").catch(() => ""),
                );
                const stem = file.replace(/\.md$/, "");
                const id = label + ": " + stem;
                const title = fm.title ?? stem;
                const existing = byId.get(id);
                if (existing) {
                  /* Keep whichever locale actually has a cover, so the
                     "already has an image" note is not lost. */
                  existing.current = existing.current ?? fm.cover ?? null;
                  continue;
                }
                byId.set(id, { id, title, current: fm.cover ?? null, locale: locale.name });
              }
            }
            for (const entry of byId.values()) {
              /* One cover per entry. A gallery slot too, but only for pieces:
                 the story schema has no gallery field, so offering one would
                 be offering the artist somewhere to put an image that has
                 nowhere to go. */
              push(entry.id, entry.title + " (cover)", entry.current, label, "public/media/");
              if (name === "pieces") {
                push(
                  entry.id + " — gallery",
                  entry.title + " (gallery)",
                  null,
                  label,
                  "public/media/",
                );
              }
            }          }
          /* Frontmatter can name a cover that was never committed, or that
             was removed by a later edit. Saying "already has an image" about
             a file that is not there is how the artist ends up wondering where
             their photograph went, so the claim is only made if the file is
             really there. */
          for (const s of slots) {
            if (!s.current) continue;
            const rel = String(s.current).replace(/^\/?(public\/)?/, "");
            const abs = path0.join(root, "public", rel);
            if (!(await fs.stat(abs).catch(() => null))?.isFile()) s.current = null;
          }
          return slots;
        };

        /**
         * Questions and permissions that are still waiting on a human.
         *
         * The SSE event is not enough on its own: it is transient, so a page
         * that is closed or reloaded at the wrong moment never learns about
         * it, the assistant sits on `status: "running"` forever, and
         * `session.idle` never fires so nothing looks wrong. Polling the
         * authoritative list makes a pending prompt survive a reload, and lets
         * the page be re-opened months later and still unblock the turn.
         *
         * These are the workspace-wide endpoints on purpose — the
         * session-scoped `/api/session/:id/question` returns an empty list for
         * a pending question, which is exactly the case that matters here.
         */
        const pendingPrompts = async () => {
          const id = await ensureSession();
          const ask = async (path) => {
            try {
              const res = await upstream(path);
              const body = await res.json();
              const list = Array.isArray(body) ? body : (body?.data ?? []);
              return list.filter((r) => !r?.sessionID || r.sessionID === id);
            } catch {
              return [];
            }
          };
          const [questions, permissions] = await Promise.all([
            ask("/question"),
            ask("/permission"),
          ]);
          return { questions, permissions, imageRequests: openImageRequests() };
        };

        const messages = async () => {
          const id = await ensureSession();
          const res = await upstream(`/session/${id}/message`);
          return res.json();
        };

        /**
         * Absolute paths the agent actually wrote, taken from the `patch`
         * parts of the session. This is the ONLY reliable record of what the
         * agent touched: /session/:id/diff, session.diff events and
         * session.summary are all empty on opencode 1.18.32.
         */
        const touchedFiles = async () => {
          const list = await messages();
          const files = new Set();
          for (const message of list) {
            for (const part of message.parts ?? []) {
              if (part.type !== "patch" || !Array.isArray(part.files)) continue;
              for (const file of part.files) files.add(file);
            }
          }
          return files;
        };

        /**
         * Run a git subcommand and resolve with stdout. Never throws on a
         * non-zero exit: callers decide whether a failure matters.
         */
        const git = (args, { timeout = 120_000 } = {}) =>
          new Promise((resolve) => {
            execFile(
              "git",
              args,
              {
                cwd: options.root ?? process.cwd(),
                maxBuffer: 8_000_000,
                timeout,
                env: {
                  ...process.env,
                  GIT_TERMINAL_PROMPT: "0",
                  GIT_ASKPASS: "echo",
                  GIT_CONFIG_COUNT: "1",
                  GIT_CONFIG_KEY_0: "commit.gpgsign",
                  GIT_CONFIG_VALUE_0: "false",
                },
              },
              (err, stdout, stderr) =>
                resolve({
                  code: err ? (err.code ?? 1) : 0,
                  stdout: String(stdout ?? ""),
                  stderr: String(stderr ?? "").trim(),
                }),
            );
          });

        /** The current branch name, or null when detached / not a repo. */
        const currentBranch = async () => {
          const { stdout } = await git(["rev-parse", "--abbrev-ref", "HEAD"]);
          const name = stdout.trim();
          return name && name !== "HEAD" ? name : null;
        };

        /**
         * Everything that a `git add -A && git commit` would sweep up, so the
         * publish dialog can show the human exactly what leaves their machine.
         * This is deliberately NOT narrowed to the files the assistant
         * touched: a publish button that silently filtered would make the
         * commit and the preview disagree.
         */
        const publishPreview = async () => {
          const cwd = options.root ?? process.cwd();
          const [status, branch, diffstat, ahead, remote] = await Promise.all([
            git(["status", "--porcelain", "--untracked-files=all"]),
            currentBranch(),
            git(["diff", "--stat", "HEAD"]),
            git(["rev-list", "--count", "@{u}..HEAD"]).catch(() => ({ stdout: "0" })),
            git(["remote", "get-url", "origin"]),
          ]);

          const files = status.stdout
            .split("\n")
            .filter((line) => line.trim().length > 0)
            .map((line) => ({
              code: line.slice(0, 2).trim(),
              file: line.slice(3).replace(/^"(.*)"$/, "$1"),
            }));

          return {
            branch,
            remote: remote.stdout.trim() || null,
            unpublishedCommits: Number.parseInt(ahead.stdout.trim(), 10) || 0,
            files,
            dirty: files.length > 0,
            diffstat: diffstat.stdout.trim(),
            root: cwd,
          };
        };

        /**
         * Commit the working tree, then push it.
         *
         * `target` is either "branch" (push the checked-out branch, which for
         * a Cloudflare Pages project only produces a *preview* deploy) or
         * "main" (push this branch's commits onto main, which is the live
         * deploy). Never force-pushes: if the remote has moved, the push fails
         * and the local commit is kept.
         */
        const publish = async (message, target) => {
          const branch = await currentBranch();
          if (!branch) return { ok: false, error: "Detached HEAD — check out a branch first." };

          const toMain = target === "main";
          if (toMain && branch === "main") toMain = false;
          const refspec = toMain ? "HEAD:main" : "HEAD:" + branch;

          /* Pushing to main skips review entirely, so make sure the branch is
             not wildly behind: an old main would make this a non-fast-forward
             and the push will fail anyway. Better to say so up front. */
          if (toMain) {
            await git(["fetch", "origin", "main"], { timeout: 120_000 });
            const behind = await git(["rev-list", "--count", "HEAD..origin/main"]);
            const n = Number.parseInt(behind.stdout.trim(), 10) || 0;
            if (n > 0) {
              return {
                ok: false,
                error: "This branch is " + n + " commit(s) behind origin/main, " +
                  "so pushing it to main would be rejected.",
                hint: "Rebase or merge origin/main first: git pull --rebase origin main",
              };
            }
          }

          const preview = await publishPreview();
          if (!preview.dirty && preview.unpublishedCommits === 0) {
            return { ok: false, error: "Nothing to publish — the working tree is clean." };
          }

          const log = [];
          if (preview.dirty) {
            const add = await git(["add", "-A"]);
            if (add.code !== 0) {
              return { ok: false, error: "git add failed: " + (add.stderr || add.code) };
            }
            const msg = (String(message || "").trim() || "content: update the site").slice(0, 300);
            const commit = await git(["commit", "-m", msg]);
            if (commit.code !== 0) {
              if (/nothing to commit/i.test(commit.stdout + commit.stderr)) {
                return { ok: false, error: "Nothing changed after all." };
              }
              return { ok: false, error: "git commit failed: " + (commit.stderr || commit.stdout) };
            }
            log.push(commit.stdout.trim().split("\n")[0]);
          }

          const push = await git(["push", "origin", refspec], { timeout: 300_000 });
          if (push.code !== 0) {
            return {
              ok: false,
              error: "Committed locally, but the push failed: " + (push.stderr || push.stdout).slice(0, 400),
              hint: "Your work is safe in the commit. Push by hand when ready.",
              committed: log,
            };
          }
          log.push(push.stdout.trim());

          const sha = await git(["rev-parse", "--short", "HEAD"]);
          return {
            ok: true,
            branch,
            pushedTo: toMain ? "main" : branch,
            live: toMain,
            sha: sha.stdout.trim(),
            log,
          };
        };

        /**
         * Working-tree diff narrowed to the files this session touched.
         * Uses opencode's git-backed /vcs endpoints, not /session/:id/diff.
         */
        const diff = async () => {
          const [vcsDiff, vcsInfo, touched, tree] = await Promise.all([
            upstream("/vcs/diff?mode=git").then((r) => r.json()),
            upstream("/vcs").then((r) => r.json()).catch(() => ({})),
            touchedFiles(),
            gitStatus(),
          ]);

          const root = options.root ?? process.cwd();
          const relative = (abs) =>
            abs.startsWith(root + "/") ? abs.slice(root.length + 1) : abs;

          const mine = new Set([...touched].map(relative));
          const byFile = new Map(vcsDiff.map((e) => [e.file, e]));
          const files = [];
          const untracked = [];
          const clean = [];

          for (const file of mine) {
            const entry = byFile.get(file);
            if (entry) {
              files.push({ ...entry, ours: true });
              continue;
            }
            const code = tree.get(file);
            if (code === "??") {
              // A new file the agent created. There is nothing to diff it
              // against, so show its content instead of claiming no change.
              let content = "";
              try {
                const res = await upstream(
                  `/file/content?path=${encodeURIComponent(file)}`,
                );
                const body = await res.json();
                content = typeof body?.content === "string" ? body.content : "";
              } catch {
                content = "";
              }
              untracked.push({
                file,
                status: "added",
                additions: content ? content.split("\n").length : 0,
                deletions: 0,
                patch: null,
                preview: content.slice(0, 4000),
                ours: true,
              });
              continue;
            }
            // Tracked, but identical to HEAD — typically because the change was
            // undone. Saying "untracked" here would be a lie, so say nothing
            // changed instead.
            clean.push(file);
          }

          return { branch: vcsInfo?.branch ?? null, files, untracked, clean };
        };

        /**
         * `git status --porcelain` as a Map of path -> status code.
         *
         * This is the one thing opencode's API will not tell us: /vcs/status
         * lists tracked modifications only, so a file the agent just created
         * is indistinguishable from one that was edited and then undone.
         * Read-only, no shell, no dependency.
         */
        const gitStatus = () =>
          new Promise((resolve) => {
            execFile(
              "git",
              ["status", "--porcelain", "--untracked-files=all"],
              { cwd: options.root ?? process.cwd(), maxBuffer: 4_000_000 },
              (err, stdout) => {
                const map = new Map();
                if (err) return resolve(map);
                for (const line of String(stdout).split("\n")) {
                  if (line.length < 4) continue;
                  const code = line.slice(0, 2);
                  let file = line.slice(3);
                  // "old -> new" for renames; keep the new path.
                  if (file.includes(" -> ")) file = file.split(" -> ").pop();
                  if (file.includes('"') && file.startsWith('"')) {
                    file = file.slice(1, -1);
                  }
                  map.set(file, code);
                }
                resolve(map);
              },
            );
          });

        /** SSE relay: opencode /event -> browser. Same-origin, so no CORS. */
        const events = async (req, res) => {
          const ac = new AbortController();
          req.on("close", () => ac.abort());
          let remote;
          try {
            remote = await fetch(`${base}/event`, {
              headers: { accept: "text/event-stream" },
              signal: ac.signal,
            });
          } catch (err) {
            res.writeHead(502, { "content-type": "text/plain" });
            res.end(`opencode server unreachable: ${err.message}`);
            return;
          }
          res.writeHead(200, {
            "content-type": "text/event-stream; charset=utf-8",
            "cache-control": "no-cache, no-transform",
            connection: "keep-alive",
            "x-accel-buffering": "no",
          });
          const body = Readable.fromWeb(remote.body);
          body.on("error", () => res.end());
          req.on("close", () => body.destroy());
          body.pipe(res);
        };

        const handler = async (req, res) => {
          const url = new URL(req.url ?? "/", "http://localhost");
          // server.middlewares.use("/_assistant", …) strips the prefix, so
          // req.url here is already relative to /_assistant.
          const path = url.pathname.replace(/\/+$/, "") || "/";
          const method = req.method ?? "GET";

          if (method === "OPTIONS") {
            res.writeHead(204, { allow: "GET, POST, OPTIONS" });
            res.end();
            return;
          }

          // Reject cross-origin callers. A page on any other site could
          // otherwise drive this agent, which has file-write access.
          const origin = req.headers.origin;
          if (origin) {
            let originHost;
            try {
              originHost = new URL(origin).host;
            } catch {
              json(res, 403, { error: "bad origin" });
              return;
            }
            if (originHost !== req.headers.host) {
              json(res, 403, { error: "cross-origin requests are not allowed" });
              return;
            }
          }

          try {
            /* ---- the page ---------------------------------------------- */
            if (path === "/" && method === "GET") {
              assertPageParses();
              res.writeHead(200, {
                "content-type": "text/html; charset=utf-8",
                "cache-control": "no-store",
              });
              res.end(PAGE);
              return;
            }

            /* ---- server health ----------------------------------------- */
            if (path === "/health" && method === "GET") {
              const ok = await health();
              json(res, ok ? 200 : 503, {
                ok: Boolean(ok),
                version: ok?.version ?? null,
                base,
                sessionID: sessionID ?? null,
              });
              return;
            }

            /* ---- session ----------------------------------------------- */
            if (path === "/session" && method === "GET") {
              const id = await ensureSession();
              const vcs = await upstream("/vcs")
                .then((r) => r.json())
                .catch(() => ({}));
              json(res, 200, { sessionID: id, branch: vcs?.branch ?? null });
              return;
            }
            if (path === "/session" && method === "POST") {
              const body = await readBody(req);
              const id = await ensureSession(Boolean(body.reset));
              json(res, 200, { sessionID: id });
              return;
            }

            /* ---- history ----------------------------------------------- */
            if (path === "/messages" && method === "GET") {
              const [list, pending] = await Promise.all([messages(), pendingPrompts()]);
              json(res, 200, { messages: list, pending });
              return;
            }

            /* ---- SSE ----------------------------------------------------- */
            if (path === "/events" && method === "GET") {
              await events(req, res);
              return;
            }

            /* ---- chat ---------------------------------------------------- */
            if (path === "/chat" && method === "POST") {
              const body = await readBody(req);
              const text = String(body.text ?? "").trim();
              if (!text) {
                json(res, 400, { error: "empty message" });
                return;
              }
              /* Snapshot before the model touches anything. The turn that
                 flattened the homepage palette also gutted a component, and
                 "revert" only helps if you notice. This is the cheap belt to
                 that braces: a full copy of the text sources, a few hundred
                 KB, before the first tool call of every message. */
              const snap = await snapshot();
              if (snap) {
                logger.info(`assistant: snapshot ${snap.dir}`);
              }
              const id = await ensureSession();
              // agent: "build" is required. The default agent is "plan", which
              // is read-only and would silently refuse to change anything.
              const res2 = await upstream(`/session/${id}/prompt_async`, {
                method: "POST",
                headers: { "content-type": "application/json" },
                body: JSON.stringify({
                  agent: "build",
                  system: SYSTEM_PROMPT,
                  parts: [{ type: "text", text }],
                }),
              });
              json(res, 200, { sessionID: id, queued: res2.status === 204 });
              return;
            }

            /* ---- diff ----------------------------------------------------- */
            if (path === "/diff" && method === "GET") {
              json(res, 200, await diff());
              return;
            }

            /* ---- undo ----------------------------------------------------- */
            if (path === "/revert" && method === "POST") {
              const body = await readBody(req);
              if (!body.messageID) {
                json(res, 400, { error: "messageID is required" });
                return;
              }
              const id = await ensureSession();
              const res2 = await upstream(`/session/${id}/revert`, {
                method: "POST",
                headers: { "content-type": "application/json" },
                body: JSON.stringify(
                  body.partID
                    ? { messageID: body.messageID, partID: body.partID }
                    : { messageID: body.messageID },
                ),
              });
              const session = await res2.json();
              // Content edits do not need a dev-server restart, but Astro's
              // in-memory content cache does need to be told.
              if (typeof refreshContent === "function") {
                await refreshContent().catch(() => {});
              }
              json(res, 200, { ok: true, reverted: session?.revert ?? null });
              return;
            }

            /* ---- permission prompts --------------------------------------- */
            if (path === "/permission" && method === "POST") {
              const body = await readBody(req);
              const response = body.response;
              // Measured against 1.18.32: the enum is once | always | reject.
              if (!["once", "always", "reject"].includes(response)) {
                json(res, 400, { error: "response must be once, always or reject" });
                return;
              }
              const id = await ensureSession();
              const res2 = await upstream(
                `/session/${id}/permissions/${encodeURIComponent(body.permissionID ?? "")}`,
                {
                  method: "POST",
                  headers: { "content-type": "application/json" },
                  body: JSON.stringify({ response }),
                },
              );
              json(res, 200, { ok: res2.ok });
              return;
            }

            /* ---- give up on a turn that is not going anywhere -------------
               A question tool call can end up "running" with no entry in
               /question at all, which is unrecoverable by replying: there is
               no id to reply to and no reject either. The turn then sits at
               status "running" forever and the page just stops. Aborting the
               session is the only thing that clears it, and the tool part
               comes back with an error the artist can read. */
            if (path === "/abort" && method === "POST") {
              const id = await ensureSession();
              const res2 = await upstream(`/session/${id}/abort`, { method: "POST" });
              logger.info("assistant: turn aborted from the panel");
              json(res, res2.ok ? 200 : 502, { ok: res2.ok });
              return;
            }

            /* ---- clarifying questions -------------------------------------- */
            if (path === "/question" && method === "POST") {
              const body = await readBody(req);
              /* No id is needed for the call itself, but make sure a session
                 exists first: replying into nothing would fail for a reason
                 that has nothing to do with the question. */
              await ensureSession();
              const rid = encodeURIComponent(body.questionID ?? "");
              /* Workspace-level, not /api/session/:id/question/:rid. That form
                 answers 404 QuestionNotFoundError for a question the same
                 server is currently listing — the request id is in the shared
                 store, not in a per-session one. Measured against a real
                 question mid-turn: the list shows it, the session-scoped
                 reply says it does not exist. The artist clicks a button,
                 nothing happens, and the turn stays wedged. */
              if (body.reject) {
                await upstream(`/question/${rid}/reject`, {
                  method: "POST",
                });
              } else {
                const answers = Array.isArray(body.answers) ? body.answers : [];
                await upstream(`/question/${rid}/reply`, {
                  method: "POST",
                  headers: { "content-type": "application/json" },
                  body: JSON.stringify({ answers }),
                });
              }
              json(res, 200, { ok: true });
              return;
            }

            /* ---- refresh the local preview -------------------------------- */
            /* `npm run routes` regenerates the dynamic page files under
               src/pages, then refreshContent() tells Astro to re-read the
               content collections so the new routes actually serve. */
            if (path === "/preview/refresh" && method === "POST") {
              const root = options.root ?? process.cwd();
              const routes = await new Promise((resolve) => {
                execFile(
                  process.execPath,
                  ["scripts/generate-routes.mjs"],
                  { cwd: root, maxBuffer: 4_000_000, timeout: 120_000 },
                  (err, stdout, stderr) =>
                    resolve({
                      code: err ? (err.code ?? 1) : 0,
                      stdout: String(stdout ?? "").trim(),
                      stderr: String(stderr ?? "").trim(),
                    }),
                );
              });
              if (routes.code !== 0) {
                json(res, 500, {
                  error: "Regenerating routes failed.",
                  detail: (routes.stderr || routes.stdout || "").slice(0, 500),
                });
                return;
              }
              if (typeof refreshContent === "function") await refreshContent();
              json(res, 200, { ok: true, routes: routes.stdout });
              return;
            }

            /* ---- publish the working tree to the live site ----------------- */
            if (path === "/publish/preview" && method === "POST") {
              json(res, 200, { ok: true, preview: await publishPreview() });
              return;
            }

            if (path === "/publish" && method === "POST") {
              const body = await readBody(req);
              if (body.confirm !== "publish") {
                json(res, 400, { error: "Publishing needs an explicit confirmation." });
                return;
              }
              const target = body.target === "main" ? "main" : "branch";
              const result = await publish(body.message, target);
              json(res, result.ok ? 200 : 400, result);
              return;
            }

            /* ---- add an image the artist picked from their own disk --------- */
            if (path === "/snapshots" && method === "GET") {
              const home = path0.join(os.tmpdir(), "felp011-assistant");
              const names = (await fs.readdir(home).catch(() => [])).sort().reverse();
              json(res, 200, { dir: home, snapshots: names });
              return;
            }

            /* ---- what the picker should offer ---------------------------- */
            if (path === "/slots" && method === "GET") {
              const only = (url.searchParams.get("collection") || "").trim();
              json(res, 200, { slots: await imageSlots(only || null) });
              return;
            }

            /* ---- ask_for_image: register, then wait for the answer -------- */
            if (path === "/image-request" && method === "POST") {
              const body = await readBody(req);
              const id =
                Date.now().toString(36) + "-" + Math.random().toString(36).slice(2, 8);
              imageRequests.set(id, {
                purpose: String(body.purpose ?? "").trim() || "an image",
                slot: body.slot ? String(body.slot).trim() : null,
                destination: body.destination ? String(body.destination).trim() : null,
                overwrite: Boolean(body.overwrite),
                sessionID: body.sessionID ?? null,
                messageID: body.messageID ?? null,
                status: "pending",
                createdAt: Date.now(),
              });
              logger.info(`assistant: image request ${id} (${body.purpose ?? ""})`);
              json(res, 200, { id });
              return;
            }

            if (path.startsWith("/image-request/") && method === "GET") {
              const id = decodeURIComponent(path.slice("/image-request/".length));
              const req = imageRequests.get(id);
              if (!req) {
                json(res, 404, { error: "no such image request" });
                return;
              }
              json(res, 200, {
                id,
                status: req.status,
                path: req.path ?? null,
                publicPath: req.publicPath ?? null,
                storedAs: req.storedAs ?? null,
                renamedBecauseTaken: Boolean(req.renamedBecauseTaken),
                slot: req.slot ?? null,
                error: req.error ?? null,
              });
              return;
            }

            if (path.startsWith("/image-request/") && method === "POST") {
              const id = decodeURIComponent(path.slice("/image-request/".length));
              const body = await readBody(req).catch(() => ({}));
              const status = body.action === "skip" ? "skipped" : "failed";
              if (!answerImageRequest(id, { status, error: body.error ?? null })) {
                json(res, 404, { error: "no such open image request" });
                return;
              }
              json(res, 200, { id, status });
              return;
            }

            if (path === "/upload" && method === "POST") {
              const root = options.root ?? process.cwd();
              const body = await readBody(req, 20_000_000);
              /* The browser sends a data: URL, but strip the prefix before
                 decoding. Buffer.from(x, "base64") does NOT skip the "data:"
                 header: it decodes "data:image/png;base64" as base64
                 characters too, which shifts every byte and makes a real PNG
                 fail its own magic-byte check. */
              const data = String(body.data ?? "").replace(/^data:[^,]*,/, "");
              /* Sanitise the filename server-side as well as in the browser.
                 The client already cleans it, but an endpoint that depends on
                 that is not a trust boundary: "My Photo (1).JPG" would land on
                 disk with spaces and brackets and break its own static URL. */
              const name = safeUploadName(String(body.name ?? "").trim());
              let dest = String(body.path ?? "").trim();
              /* Check the RAW path for ".." before path.join normalises it
                 away. Doing this after the join is useless: "/../../../../tmp/x.png"
                 becomes "/tmp/x.png" and the ".." is already gone, so the
                 request then quietly succeeds writing into a stray tmp/ folder
                 inside the project. Refuse before anything rewrites the path. */
              if (dest.split(/[\\/]/).includes("..")) {
                json(res, 400, { error: "path must not contain .." });
                return;
              }
              /* Never take the folder from the client unchecked. A name like
                 "../../secrets.png" must not be able to steer the write. */
              if (name) {
                const typed = dest.replace(/\/+$/, "");
                dest = path0.extname(typed) ? path0.join(path0.dirname(typed), name) : typed + "/" + name;
              }

              if (!dest) {
                json(res, 400, { error: "path is required" });
                return;
              }
              /* Containment is still checked on the resolved path below, in
                 case a symlink points outside the project. */
              /* A bare folder like "/public/media" once created a FILE called
                 media, then media-2, media-3... With no name to fall back on
                 there is nothing to call it, so say so. */
              if (!path0.extname(dest) && !name) {
                json(res, 400, { error: "path must include a filename" });
                return;
              }

              const abs = path0.resolve(root, dest.replace(/^\/+/, ""));
              const inRepo =
                abs === path0.resolve(root) ||
                abs.startsWith(path0.resolve(root) + path0.sep);
              if (!inRepo) {
                json(res, 400, { error: "path must stay inside the project" });
                return;
              }
              /* Follow symlinks before writing. A path that is textually
                 inside the repo can still resolve outside it, which would let
                 a link planted in public/ redirect a write anywhere on disk. */
              const real = await fs.realpath(path0.dirname(abs)).then(
                (d) => path0.resolve(d),
                () => null,
              );
              if (real) {
                const realRoot = await fs.realpath(root);
                if (real !== realRoot && !real.startsWith(realRoot + path0.sep)) {
                  json(res, 400, { error: "path must stay inside the project" });
                  return;
                }
              }

              const ext = path0.extname(name || dest).toLowerCase();
              if (!ALLOWED_IMAGE_EXT.includes(ext)) {
                json(res, 400, {
                  error: "unsupported file type" + (ext ? " (" + ext + ")" : ""),
                  allowed: ALLOWED_IMAGE_EXT.join(", "),
                });
                return;
              }

              /* Base64 inflates by 4/3; the media prebuild rejects anything
                 over 8MB, so refuse early with a message worth reading. */
              const bytes = Buffer.from(data, "base64");
              if (!bytes.length) {
                json(res, 400, { error: "the file arrived empty" });
                return;
              }
              if (bytes.length > 8 * 1024 * 1024) {
                json(res, 413, { error: "image is larger than 8MB" });
                return;
              }
              if (!looksLikeImage(bytes)) {
                json(res, 415, {
                  error: "that is not a real image file (the extension lies)",
                });
                return;
              }

              await fs.mkdir(path0.dirname(abs), { recursive: true });
              /* Never clobber. The artist's photographs are not in git and
                 cannot be recovered, so a same-name upload becomes a new
                 numbered file instead of destroying the original. Overwrite
                 has to be asked for explicitly. */
              const exists = await fs.access(abs).then(() => true).catch(() => false);
              if (exists && !body.replace) {
                const stem = path0.basename(dest, path0.extname(dest));
                const ext = path0.extname(dest);
                let free = null;
                for (let n = 2; n < 200; n++) {
                  const candidate = path0.join(path0.dirname(abs), `${stem}-${n}${ext}`);
                  if (!(await fs.access(candidate).then(() => true).catch(() => false))) {
                    free = candidate;
                    break;
                  }
                }
                if (!free) {
                  json(res, 409, { error: "too many files with that name" });
                  return;
                }
                var finalAbs = free;
              } else {
                var finalAbs = abs;
              }
              await fs.writeFile(finalAbs, bytes);

              const rel = path0
                .relative(root, finalAbs)
                .split(path0.sep)
                .join("/");
              const pubRel = path0
                .relative(path0.join(root, "public"), finalAbs)
                .split(path0.sep)
                .join("/");
              const publicPath = pubRel.startsWith("..") ? null : "/" + pubRel;
              /* If this upload was answering an ask_for_image tool call, close
                 that request out. The tool is blocked on a poll of this
                 record, so nothing else needs to tell it. */
              const requestID = body.requestID ? String(body.requestID) : "";
              if (requestID) {
                const closed = answerImageRequest(requestID, {
                  status: "done",
                  path: "/" + rel,
                  publicPath,
                  storedAs: path0.basename(finalAbs),
                  /* Only the model's own proposal stays if the artist did not
                     move it, so an empty or bogus field cannot erase it. */
                  slot: body.slot ? String(body.slot) : null,
                  renamedBecauseTaken: exists && !body.replace,
                });
                if (closed) {
                  logger.info(`assistant: image request ${requestID} answered`);
                } else {
                  /* The picker was reloaded or the request expired. The file
                     is on disk either way, so this is not an error worth
                     failing the upload over. */
                  logger.warn(`assistant: upload for unknown image request ${requestID}`);
                }
              }
              logger.info(
                `assistant: image ${exists ? (body.replace ? "replaced" : "kept both") : "added"} ${rel} (${bytes.length}b)`,
              );
              json(res, 200, {
                ok: true,
                path: "/" + rel,
                publicPath,
                bytes: bytes.length,
                renamedBecauseTaken: exists && !body.replace,
                replaced: exists && !!body.replace,
              });
              return;
            }

            /* ---- tell Astro to re-read the content collections ------------ */
            if (path === "/refresh" && method === "POST") {
              if (typeof refreshContent !== "function") {
                json(res, 501, { error: "refreshContent unavailable" });
                return;
              }
              await refreshContent();
              json(res, 200, { ok: true });
              return;
            }

            json(res, 404, { error: `no assistant route ${method} ${path}` });
          } catch (err) {
            const down = /fetch failed|ECONNREFUSED|unreachable|aborted/i.test(
              String(err?.message ?? err),
            );
            if (down) {
              json(res, 503, {
                error: `Cannot reach the opencode server at ${base}.`,
                hint: "Start it with: opencode serve --port 4096 --hostname 127.0.0.1",
              });
              return;
            }
            logger.error(`assistant: ${err?.message ?? err}`);
            json(res, 500, { error: String(err?.message ?? err) });
          }
        };

        // No next() call: everything under /_assistant is ours, and falling
        // through to Astro would 404. Verified both /_assistant and
        // /_assistant/ serve the page.
        server.middlewares.use("/_assistant", (req, res) => {
          handler(req, res).catch((err) => {
            logger.error(`assistant: unhandled ${err?.message ?? err}`);
            if (!res.headersSent) json(res, 500, { error: "assistant failure" });
            else res.end();
          });
        });

        logger.info(
          `assistant: /_assistant ready (opencode at ${base}) — dev only, never built`,
        );
      },
    },
  };
}

/**
 * The page's script lives inside a template literal, so one single backslash
 * — `.split("\n")` written where `.split("\\n")` was meant — silently becomes
 * a real newline in the served HTML and the whole script fails to parse. The
 * page then loads, shows its static "connecting…" forever and no button does
 * anything, because not one line of it ever ran. That shipped once and made
 * the assistant look broken for hours. Compiling the script before it is sent
 * turns that into a loud 500 instead of a mystery.
 */
let pageChecked = false;
function assertPageParses() {
  if (pageChecked) return;
  const from = PAGE.indexOf("<script>");
  const to = PAGE.indexOf("</script>");
  const js = PAGE.slice(from + 8, to);
  try {
    new Function(js);
  } catch (err) {
    // `new Function` does not report a usable line number, so find the
    // offending line directly: a string literal broken by a raw newline always
    // leaves an odd number of unescaped quotes on its line.
    const lines = js.split("\n");
    const suspect = lines.findIndex((l) => {
      let open = false;
      for (let i = 0; i < l.length; i++) {
        if (l[i] === "\\") { i++; continue; }
        if (l[i] === '"') open = !open;
      }
      return open;
    });
    const ctx = suspect === -1 ? "" :
      `\nline ${suspect + 1}: ${lines[suspect].trim().slice(0, 160)}`;
    throw new Error(
      `the /_assistant page script does not compile: ${err.message}${ctx}\n` +
      "Almost always a single backslash inside the PAGE template literal " +
      "that should be doubled. Write \\\\n and \\\\s, never \\n and \\s.",
    );
  }
  assertBehaviourSurvived(js);
  pageChecked = true;
}

/**
 * Check that the page still *behaves*, not just that it compiles.
 *
 * new Function tells you the script is syntactically valid. It cannot tell
 * you the meaning survived. A single \s inside the PAGE template literal is
 * eaten and arrives in the browser as a plain "s", so the upload detector
 * compiled fine, matched nothing, and the image picker simply never appeared.
 * Nothing threw anywhere. That is the worst failure mode available: a feature
 * that is absent and silent.
 *
 * So assert the real thing. Each of these is a one-line contract the page
 * depends on, and each fails loudly at boot if a backslash gets eaten again.
 */
function assertBehaviourSurvived(js) {
  const probes = [
    {
      what: 'the [upload] header still matches',
      /* Mirrors the detector in promptCard. */
      re: (() => {
        const m = /const isAsk = (\/\^.*?\/i)\.exec/.exec(js);
        return m ? new RegExp(m[1].slice(1, -2), "i") : null;
      })(),
      yes: "[upload] a hero image for the gallery",
      no: "Which colour do you prefer?",
    },
    {
      what: "a /public/... path is still recognised in a question",
      re: (() => {
        const m = /const guess = (\/\^.*?\/i)\.exec/.exec(js) ||
          /const guess = (\/.*?\/i)\.exec/.exec(js);
        return m ? new RegExp(m[1].slice(1, -2), "i") : null;
      })(),
      yes: "put it at /public/media/hero.png please",
      no: "put it somewhere sensible",
    },
  ];
  const broken = [];
  for (const p of probes) {
    if (!p.re) { broken.push(p.what + " (probe pattern not found in the page)"); continue; }
    if (!p.re.test(p.yes) || p.re.test(p.no)) {
      broken.push(`${p.what} (regex is ${p.re})`);
    }
  }
  if (broken.length) {
    throw new Error(
      "the /_assistant page compiles but has lost behaviour:\n" +
        broken.map((b) => "  " + b).join("\n") +
        "\nAlmost always a single backslash inside the PAGE template literal. " +
        "Write \\\\s, \\\\w and \\\\\\[ there, never \\s or \\[.",
    );
  }
}

/**
 * Catch regex escapes the template literal ate.
 *
 * new Function only tells you the script is syntactically valid. It cannot
 * tell you the *meaning* survived: a single \s inside the PAGE literal
 * becomes a plain "s", and the upload detector silently stopped matching, so
 * the image picker never appeared and nothing anywhere threw. The page
 * "worked". It was just quietly wrong, which is the worst failure mode there
 * is.
 *
 * So check the source text, before the template does its damage: any regex
 * literal here must have its backslashes doubled.
 */
function assertNoStolenEscapes(js) {
  const stolen = [];
  for (const re of js.matchAll(/\/(?:\\.|\[(?:\\.|[^\]])*\]|[^/\\\n])+\/[gimsuyd]*/g)) {
    /* A correct one has \\\\ in the served text, because the template ate
       half of it. A bare \s, \d, \w, \b or \[ means the source forgot. */
    const bad = /(?<!\\)\\(s|d|w|b|n|t|r|f|v|0|ux|u\{|c|[0-9])/.exec(re[0]);
    if (bad) {
      stolen.push({ text: re[0].slice(0, 60), at: re.index });
    }
  }
  if (stolen.length) {
    const where = stolen
      .map((s) => `  line ${js.slice(0, s.at).split("\n").length}: ${s.text}`)
      .join("\n");
    throw new Error(
      "the /_assistant page has regex escapes the template literal consumed:\n" +
        where +
        "\nA single backslash in PAGE becomes nothing. Write \\\\s and \\\\[.",
    );
  }
}

